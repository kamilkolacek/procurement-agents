"""Per-category generation profile: volume, source mix, vendor count, prices, descriptions.

Templates use these slots: {month} {n} {ref} {item} {city} {qtr}. Goods categories list
`items` as (name, unit_low, unit_high); their PO lines carry an item code and quantity.
"""

